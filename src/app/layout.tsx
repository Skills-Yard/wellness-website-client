import type { Metadata } from "next";
import { Inter, Geist_Mono, Abyssinica_SIL } from "next/font/google";
import "./globals.css";
import Footer from "@/src/components/home/footer";
import { CartProvider } from "@/src/context/CartContext";
import { CategoryProvider } from "@/src/context/CategoryContext";
import Navbar from "@/src/components/home/navbar";
import Providers from "./providers";
import PushNotificationBootstrap from "@/src/components/notifications/PushNotificationBootstrap";

// App typeface — Inter, per the Frame 158 design system. Keeps the
// existing `--font-geist-sans` CSS variable name so `--font-sans` /
// `font-sans` wiring in globals.css stays untouched.
const geistSans = Inter({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Backs the existing `font-serif` utility (see globals.css's --font-serif
// override) — matches the decorative headline font used in the Figma specs
// for WallPanel and Inspotlight card titles.
const abyssinicaSIL = Abyssinica_SIL({
  weight: "400",
  variable: "--font-abyssinica-sil",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Eezit-client",
  description: "Generated by create next app",
};

export const viewport = {
  width: "device-width",
  initialScale: 1,
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${abyssinicaSIL.variable} h-full antialiased`}
    >
      <body
        className="min-h-full flex flex-col"
        suppressHydrationWarning
      >
        <Providers>
          {/* CartProvider resolves the browsing zone; CategoryProvider reads
              it from here (via useCart()) to fetch zone-filtered categories
              — see categoryApi.ts. */}
          <CartProvider>
            <CategoryProvider>
              <PushNotificationBootstrap />
              <Navbar />
              {children}
              <div className="hidden md:block">
                <Footer />
              </div>
            </CategoryProvider>
          </CartProvider>
        </Providers>
      </body>
    </html>
  );
}
